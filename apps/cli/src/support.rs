//! Diagnostic bundle generation: version, platform, config, features, and collection/WAL state.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::sync::Arc;

use piramid::config::Config;
use piramid::state::AppState;

/// Substrings matched case-insensitively against env var names to redact their values.
const SECRET_MARKERS: &[&str] = &[
    "KEY",
    "TOKEN",
    "SECRET",
    "PASSWORD",
    "DSN",
    "CREDENTIAL",
    "AUTH",
];

/// Environment variables Piramid reads, by prefix, reported beside the resolved config.
const REPORTED_PREFIXES: &[&str] = &["PIRAMID_", "CONFIG_FILE", "OPENAI_API_KEY"];

fn is_secret(name: &str) -> bool {
    let upper = name.to_ascii_uppercase();
    SECRET_MARKERS.iter().any(|marker| upper.contains(marker))
}

/// The inputs a support bundle is rendered from.
pub struct Bundle<'a> {
    /// The resolved configuration.
    pub config: &'a Config,
    /// The config file named on the command line, if any.
    pub config_file: Option<&'a Path>,
    /// The state whose open collections are reported.
    pub state: &'a Arc<AppState>,
    /// The name and error of each collection that failed to open.
    pub failed_collections: &'a [(String, String)],
}

/// Render the bundle as markdown.
pub fn render(bundle: &Bundle<'_>) -> String {
    let config = bundle.config;
    let state = bundle.state;
    let mut out = String::new();

    let _ = writeln!(out, "# Piramid support bundle");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "Generated by `piramid support-bundle`. Review before sharing; values that look like\n\
         credentials are redacted, but check anyway."
    );
    let _ = writeln!(out);

    let _ = writeln!(out, "## Version");
    let _ = writeln!(out);
    let _ = writeln!(out, "piramid   {}", env!("CARGO_PKG_VERSION"));
    let _ = writeln!(out, "target    {}", std::env::consts::ARCH);
    let _ = writeln!(out, "os        {}", std::env::consts::OS);
    let _ = writeln!(out);

    let _ = writeln!(out, "## Build features");
    let _ = writeln!(out);
    for (name, enabled) in [
        ("gpu-cuda", cfg!(feature = "gpu-cuda")),
        ("inference-candle", cfg!(feature = "inference-candle")),
        ("otel", cfg!(feature = "otel")),
    ] {
        let _ = writeln!(out, "{name:<18} {}", if enabled { "on" } else { "off" });
    }
    let _ = writeln!(out);

    let _ = writeln!(out, "## Compute strategies");
    let _ = writeln!(out);
    for strategy in piramid::compute::strategies::all() {
        let _ = writeln!(
            out,
            "{:<10} {}",
            strategy.name(),
            if strategy.is_available() {
                "available"
            } else {
                "unavailable"
            }
        );
    }
    let _ = writeln!(out);

    let _ = writeln!(out, "## Runtime");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "config_file         {}",
        bundle
            .config_file
            .map_or_else(|| "none".to_string(), |p| p.display().to_string())
    );
    let _ = writeln!(out, "bind                {}", config.startup.bind);
    let _ = writeln!(out, "data_dir            {}", config.startup.data_dir);
    let _ = writeln!(
        out,
        "slow_query_ms       {}",
        config.startup.logging.slow_query_ms
    );
    let _ = writeln!(
        out,
        "embedding_provider  {}",
        config.startup.embedding.as_ref().map_or_else(
            || "none".to_string(),
            |e| format!("{} ({})", e.provider, e.model)
        )
    );
    let _ = writeln!(
        out,
        "disk_min_free       {}",
        config
            .startup
            .disk
            .min_free_bytes
            .map_or_else(|| "unset".to_string(), |b| b.to_string())
    );
    let _ = writeln!(out);

    let _ = writeln!(out, "## Environment");
    let _ = writeln!(out);
    let mut vars: Vec<(String, String)> = std::env::vars()
        .filter(|(name, _)| REPORTED_PREFIXES.iter().any(|p| name.starts_with(p)))
        .map(|(name, value)| {
            let value = if is_secret(&name) {
                format!("<redacted, {} chars>", value.len())
            } else {
                value
            };
            (name, value)
        })
        .collect();
    vars.sort();
    if vars.is_empty() {
        let _ = writeln!(out, "(none set)");
    }
    for (name, value) in vars {
        let _ = writeln!(out, "{name}={value}");
    }
    let _ = writeln!(out);

    let _ = writeln!(out, "## Collections");
    let _ = writeln!(out);
    match piramid::services::admin::metrics(state) {
        Ok(metrics) => {
            let _ = writeln!(out, "collections   {}", metrics.total_collections);
            let _ = writeln!(out, "vectors       {}", metrics.total_vectors);
            let _ = writeln!(out);
            for c in &metrics.collections {
                let _ = writeln!(out, "### {}", c.name);
                let _ = writeln!(out, "vectors        {}", c.vector_count);
                let _ = writeln!(out, "index          {}", c.index_type);
                let _ = writeln!(out, "memory_bytes   {}", c.memory_usage_bytes);
                if let Some(v) = c.insert_latency_ms {
                    let _ = writeln!(out, "insert_ms      {v:.3}");
                }
                if let Some(v) = c.search_latency_ms {
                    let _ = writeln!(out, "search_ms      {v:.3}");
                }
                if let Some(v) = c.hnsw_ef_search {
                    let _ = writeln!(out, "hnsw_ef_search {v}");
                }
                if let Some(v) = c.ivf_nprobe {
                    let _ = writeln!(out, "ivf_nprobe     {v}");
                }
                let _ = writeln!(out);
            }
            let _ = writeln!(out, "## Write-ahead log");
            let _ = writeln!(out);
            for w in &metrics.wal_stats {
                let _ = writeln!(
                    out,
                    "{:<20} size={} checkpoint_age_secs={}",
                    w.collection,
                    w.wal_size_bytes
                        .map_or_else(|| "?".into(), |b| b.to_string()),
                    w.checkpoint_age_secs
                        .map_or_else(|| "?".into(), |a| a.to_string()),
                );
            }
        }
        Err(error) => {
            let _ = writeln!(out, "failed to collect metrics: {error}");
        }
    }
    let _ = writeln!(out);

    if !bundle.failed_collections.is_empty() {
        let _ = writeln!(out, "## Collections that failed to open");
        let _ = writeln!(out);
        for (name, error) in bundle.failed_collections {
            let _ = writeln!(out, "{name}: {error}");
        }
        let _ = writeln!(out);
    }

    let _ = writeln!(out, "## Resolved configuration");
    let _ = writeln!(out);
    match yaml_serde::to_string(config) {
        Ok(yaml) => {
            let _ = writeln!(out, "```yaml");
            let _ = write!(out, "{yaml}");
            let _ = writeln!(out, "```");
        }
        Err(error) => {
            let _ = writeln!(out, "failed to serialize configuration: {error}");
        }
    }

    out
}

/// Write the rendered bundle to path.
pub fn write(bundle: &Bundle<'_>, path: &Path) -> std::io::Result<()> {
    fs::write(path, render(bundle))
}

#[cfg(test)]
mod tests {
    use super::*;
    use piramid::embeddings::EmbeddingsManager;

    fn state(name: &str) -> (Config, Arc<AppState>) {
        let dir =
            std::env::temp_dir().join(format!("piramid-support-{name}-{}", std::process::id()));
        let mut config = Config::default();
        config.startup.data_dir = dir.to_string_lossy().into_owned();
        let state = Arc::new(AppState::new(config.clone(), EmbeddingsManager::disabled()).unwrap());
        (config, state)
    }

    #[test]
    fn bundle_lists_collections_that_failed_to_open() {
        let (config, state) = state("failed");
        let failed = vec![("broken".to_string(), "manifest is corrupt".to_string())];
        let text = render(&Bundle {
            config: &config,
            config_file: None,
            state: &state,
            failed_collections: &failed,
        });
        assert!(
            text.contains("## Collections that failed to open"),
            "{text}"
        );
        assert!(text.contains("broken: manifest is corrupt"), "{text}");
    }

    #[test]
    fn bundle_names_the_config_file() {
        let (config, state) = state("config-file");
        let file = Path::new("/etc/piramid/config.yaml");
        let named = render(&Bundle {
            config: &config,
            config_file: Some(file),
            state: &state,
            failed_collections: &[],
        });
        assert!(
            named.contains("config_file         /etc/piramid/config.yaml"),
            "{named}"
        );
        assert!(!named.contains("running on defaults"), "{named}");
        let unnamed = render(&Bundle {
            config: &config,
            config_file: None,
            state: &state,
            failed_collections: &[],
        });
        assert!(unnamed.contains("config_file         none"), "{unnamed}");
        assert!(!unnamed.contains("failed to open"), "{unnamed}");
    }
}
